#!/usr/bin/env node
// Regenerates firewall/cloudflare-ips.json + firewall/origin-lock-cloudflare-ips.json from Cloudflare's published
// ranges (https://api.cloudflare.com/client/v4/ips). `--check`: exit 1 when the committed files drift (weekly CI).
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../firewall/", import.meta.url);
const res = await fetch("https://api.cloudflare.com/client/v4/ips");
const body = await res.json();
if (!res.ok || !body.success) throw new Error(`cloudflare ips: HTTP ${res.status}`);
const ips = { etag: body.result.etag, ipv4: body.result.ipv4_cidrs, ipv6: body.result.ipv6_cidrs };

const rule = {
  name: "jgc: origin lock — Cloudflare IPs only",
  description:
    "website-baseline sec.7: production requests not from Cloudflare are bypassing it. Generated by scripts/cloudflare-firewall.mjs. Stage in log mode; see kit README 'Cloudflare origin lock' before enforcing.",
  active: true,
  conditionGroup: [
    {
      conditions: [
        { type: "environment", op: "eq", value: "production" },
        { type: "ip_address", op: "inc", neg: true, value: [...ips.ipv4, ...ips.ipv6] },
        // Vercel Cron calls the deployment directly (fail-closed on CRON_SECRET); Vercel's proxy prerequisites.
        { type: "path", op: "pre", neg: true, value: "/api/cron/" },
        { type: "path", op: "pre", neg: true, value: "/.well-known/" },
      ],
    },
  ],
  action: { mitigate: { action: "log" } },
};

const files = {
  "cloudflare-ips.json": `${JSON.stringify(ips, null, 2)}\n`,
  "origin-lock-cloudflare-ips.json": `${JSON.stringify(rule, null, 2)}\n`,
};
if (process.argv.includes("--check")) {
  const drift = Object.entries(files).filter(([f, text]) => readFileSync(new URL(f, dir), "utf8") !== text);
  for (const [f] of drift) console.error(`drift: firewall/${f} — run node scripts/cloudflare-firewall.mjs, then re-stage the WAF rule`);
  process.exit(drift.length ? 1 : 0);
}
for (const [f, text] of Object.entries(files)) writeFileSync(new URL(f, dir), text);
console.log(`cloudflare ranges ${ips.etag}: ${ips.ipv4.length} v4, ${ips.ipv6.length} v6`);
